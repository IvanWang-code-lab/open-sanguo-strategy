const visualMap = new Map(generalVisualProfiles.map((profile) => [profile.id, profile]));

export const getGeneralVisualProfile = (id?: string) => {
  if (!id) return undefined;
  const visual = visualMap.get(id);
  if (visual) return visual;
  const canon = getCharacterCanonProfile(id);
  if (!canon) return undefined;
  return {
    id,
    factionColor: "#9aa4b2",
    rarityStyle: canon.rarity,
    roleStyle: canon.historicalRole,
    archetypeStyle: canon.gameArchetype,
    visualKeywords: canon.visualKeywords,
    outfitDirection: "以阵营色和角色定位生成原创文字头像，避免错用不匹配立绘。",
    accessoryHints: canon.signatureTraits,
    colorHints: canon.visualKeywords.slice(0, 3),
    portraitFallbackText: canon.name.slice(0, 2),
    flavorTitle: canon.gameArchetype,
  } satisfies GeneralVisualProfile;
};
